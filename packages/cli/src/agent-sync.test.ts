const AGENTS_START = "<!-- drever-agent-kit:start -->";
const AGENTS_END = "<!-- drever-agent-kit:end -->";
const SKILL_MARKER = "<!-- Generated by `drever agent sync`. -->";
const YAML_MARKER = "# Generated by `drever agent sync`.";
const SKILLS = [
  "drever-author-deck",
  "drever-create-deck",
  "drever-create-design",
  "drever-review-deck",
  "drever-deliver-deck",
] as const;
const CODEX_TARGETS = [
  "AGENTS.md",
  ...SKILLS.flatMap((skill) => [
    `.agents/skills/${skill}/SKILL.md`,
    `.agents/skills/${skill}/agents/openai.yaml`,
  ]),
] as const;
const CLAUDE_TARGETS = [
  "CLAUDE.md",
  ...SKILLS.map((skill) => `.claude/skills/${skill}/SKILL.md`),
] as const;

const directories: string[] = [];

const temporaryDirectory = async (name: string): Promise<string> => {
  const directory = await mkdtemp(join(tmpdir(), name));
  directories.push(directory);
  return directory;
};

const write = async (root: string, path: string, contents: string): Promise<void> => {
  const destination = join(root, path);
  await mkdir(dirname(destination), { recursive: true });
  await writeFile(destination, contents, "utf8");
};

const read = (root: string, path: string): Promise<string> => readFile(join(root, path), "utf8");

const createTemplateKit = async (version: string): Promise<string> => {
  const root = await temporaryDirectory("drever-agent-kit-");
  await write(
    root,
    "AGENTS.md",
    `${AGENTS_START}\n## Drever agent kit ${version}\n\nUse the Drever skills.\n${AGENTS_END}\n`,
  );
  await Promise.all(
    SKILLS.flatMap((skill) => [
      write(
        root,
        `skills/${skill}/SKILL.md`,
        `${SKILL_MARKER}\n---\nname: ${skill}\n---\n\n# ${skill} ${version}\n`,
      ),
      write(
        root,
        `skills/${skill}/agents/openai.yaml`,
        `${YAML_MARKER}\ninterface:\n  display_name: ${skill} ${version}\n`,
      ),
    ]),
  );
  return root;
};

afterEach(async () => {
  await Promise.all(
    directories.splice(0).map((path) => rm(path, { force: true, recursive: true })),
  );
});

